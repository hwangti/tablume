// DDL returns the CREATE statement(s) for a table or view.
func (m *Manager) DDL(id, schema string, t Table) (string, error) {
	p, err := m.pool(id)
	if err != nil {
		return "", err
	}
	ctx, cancel := metaCtx()
	defer cancel()
	conn, err := p.db.Conn(ctx)
	if err != nil {
		return "", err
	}
	defer conn.Close()
	ddl, err := p.d.DDL(ctx, conn, schema, t)
	if err != nil {
		return "", err
	}
	if strings.TrimSpace(ddl) == "" {
		return "", fmt.Errorf("%s의 DDL을 찾을 수 없습니다", t.Name)
	}
	return strings.TrimSpace(ddl) + "\n", nil
}

// rowStrings scans every row into string slices (NULL -> "").
func rowStrings(ctx context.Context, q Querier, query string, args ...any) ([][]string, error) {
	rows, err := q.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	cols, _ := rows.Columns()
	var out [][]string
	for rows.Next() {
		vals := make([]sql.NullString, len(cols))
		ptrs := make([]any, len(cols))
		for i := range vals {
			ptrs[i] = &vals[i]
		}
		if err := rows.Scan(ptrs...); err != nil {
			return nil, err
		}
		row := make([]string, len(cols))
		for i, v := range vals {
			row[i] = v.String
		}
		out = append(out, row)
	}
	return out, rows.Err()
}

// ---------------------------------------------------------------- MySQL

func (mysqlDialect) DDL(ctx context.Context, q *sql.Conn, schema string, t Table) (string, error) {
	rows, err := rowStrings(ctx, q, "SHOW CREATE TABLE "+mysqlDialect{}.QualifiedName(schema, t))
	if err != nil {
		return "", err
	}
	if len(rows) == 0 || len(rows[0]) < 2 {
		return "", nil
	}
	return rows[0][1] + ";", nil
}

// ---------------------------------------------------------------- PostgreSQL

func (pgDialect) DDL(ctx context.Context, q *sql.Conn, schema string, t Table) (string, error) {
	var oid int64
	var kind string
	err := q.QueryRowContext(ctx, `SELECT c.oid, c.relkind::text FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = $1 AND c.relname = $2`, schema, t.Name).Scan(&oid, &kind)
	if err != nil {
		return "", err
	}
	name := pgDialect{}.QualifiedName(schema, t)
	var b strings.Builder
	switch kind {
	case "v", "m":
		var def string
		if err := q.QueryRowContext(ctx, "SELECT pg_get_viewdef($1::oid, true)", oid).Scan(&def); err != nil {
			return "", err
		}
		if kind == "v" {
			fmt.Fprintf(&b, "CREATE OR REPLACE VIEW %s AS\n%s", name, strings.TrimSpace(def))
		} else {
			fmt.Fprintf(&b, "CREATE MATERIALIZED VIEW %s AS\n%s", name, strings.TrimSpace(def))
		}
		if !strings.HasSuffix(b.String(), ";") {
			b.WriteString(";")
		}
	default:
		cols, err := rowStrings(ctx, q, `SELECT quote_ident(a.attname), format_type(a.atttypid, a.atttypmod),
			a.attnotnull::text, COALESCE(pg_get_expr(d.adbin, d.adrelid), ''), a.attidentity::text, a.attgenerated::text
			FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
			WHERE a.attrelid = $1::oid AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`, oid)
		if err != nil {
			return "", err
		}
		var lines []string
		for _, c := range cols {
			l := "    " + c[0] + " " + c[1]
			switch {
			case c[4] == "a":
				l += " GENERATED ALWAYS AS IDENTITY"
			case c[4] == "d":
				l += " GENERATED BY DEFAULT AS IDENTITY"
			case c[5] == "s":
				l += " GENERATED ALWAYS AS (" + c[3] + ") STORED"
			case c[3] != "":
				l += " DEFAULT " + c[3]
			}
			if c[2] == "true" {
				l += " NOT NULL"
			}
			lines = append(lines, l)
		}
		cons, err := rowStrings(ctx, q, `SELECT quote_ident(conname), pg_get_constraintdef(oid, true) FROM pg_constraint
			WHERE conrelid = $1::oid ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 ELSE 3 END, conname`, oid)
		if err != nil {
			return "", err
		}
		for _, c := range cons {
			lines = append(lines, "    CONSTRAINT "+c[0]+" "+c[1])
		}
		fmt.Fprintf(&b, "CREATE TABLE %s (\n%s\n);", name, strings.Join(lines, ",\n"))
		idx, err := rowStrings(ctx, q, `SELECT pg_get_indexdef(indexrelid) FROM pg_index
			WHERE indrelid = $1::oid AND indexrelid NOT IN (SELECT conindid FROM pg_constraint WHERE conrelid = $1::oid)
			ORDER BY indexrelid`, oid)
		if err != nil {
			return "", err
		}
		if len(idx) > 0 {
			b.WriteString("\n")
		}
		for _, i := range idx {
			b.WriteString("\n" + i[0] + ";")
		}
	}
	comments, err := rowStrings(ctx, q, `SELECT '', obj_description($1::oid, 'pg_class') WHERE obj_description($1::oid, 'pg_class') IS NOT NULL
		UNION ALL SELECT quote_ident(a.attname), col_description($1::oid, a.attnum) FROM pg_attribute a
		WHERE a.attrelid = $1::oid AND a.attnum > 0 AND NOT a.attisdropped AND col_description($1::oid, a.attnum) IS NOT NULL`, oid)
	if err == nil && len(comments) > 0 {
		b.WriteString("\n")
		for _, c := range comments {
			lit := "'" + strings.ReplaceAll(c[1], "'", "''") + "'"
			if c[0] == "" {
				fmt.Fprintf(&b, "\nCOMMENT ON TABLE %s IS %s;", name, lit)
			} else {
				fmt.Fprintf(&b, "\nCOMMENT ON COLUMN %s.%s IS %s;", name, c[0], lit)
			}
		}
	}
	return b.String(), nil
}

// ---------------------------------------------------------------- SQL Server
// There is no built-in "script table", so it is assembled from sys.* views.

func (mssqlDialect) DDL(ctx context.Context, q *sql.Conn, db string, t Table) (string, error) {
	d := msq(db)
	s := t.Schema
	if s == "" {
		s = "dbo"
	}
	full := msq(db) + "." + msq(s) + "." + msq(t.Name)
	objFilter := `o.name = @p2 AND sc.name = @p1`
	if strings.Contains(t.Type, "VIEW") {
		rows, err := rowStrings(ctx, q, `SELECT m.definition FROM `+d+`.sys.sql_modules m
			JOIN `+d+`.sys.objects o ON o.object_id = m.object_id JOIN `+d+`.sys.schemas sc ON sc.schema_id = o.schema_id
			WHERE `+objFilter, s, t.Name)
		if err != nil || len(rows) == 0 {
			return "", err
		}
		return strings.TrimSpace(rows[0][0]) + "\nGO", nil
	}

	cols, err := rowStrings(ctx, q, `SELECT c.name, ty.name, CAST(c.max_length AS int), CAST(c.precision AS int), CAST(c.scale AS int),
		CAST(c.is_nullable AS int), CAST(c.is_identity AS int), CAST(ic.seed_value AS nvarchar(40)), CAST(ic.increment_value AS nvarchar(40)),
		dc.name, dc.definition, cc.definition
		FROM `+d+`.sys.columns c
		JOIN `+d+`.sys.objects o ON o.object_id = c.object_id
		JOIN `+d+`.sys.schemas sc ON sc.schema_id = o.schema_id
		JOIN `+d+`.sys.types ty ON ty.user_type_id = c.user_type_id
		LEFT JOIN `+d+`.sys.identity_columns ic ON ic.object_id = c.object_id AND ic.column_id = c.column_id
		LEFT JOIN `+d+`.sys.default_constraints dc ON dc.object_id = c.default_object_id
		LEFT JOIN `+d+`.sys.computed_columns cc ON cc.object_id = c.object_id AND cc.column_id = c.column_id
		WHERE `+objFilter+` ORDER BY c.column_id`, s, t.Name)
	if err != nil {
		return "", err
	}
	var lines []string
	for _, c := range cols {
		if c[11] != "" {
			lines = append(lines, "    "+msq(c[0])+" AS "+c[11])
			continue
		}
		l := "    " + msq(c[0]) + " " + mssqlType(c[1], c[2], c[3], c[4])
		if c[6] == "1" {
			l += fmt.Sprintf(" IDENTITY(%s,%s)", c[7], c[8])
		}
		if c[5] == "1" {
			l += " NULL"
		} else {
			l += " NOT NULL"
		}
		if c[10] != "" {
			l += " CONSTRAINT " + msq(c[9]) + " DEFAULT " + c[10]
		}
		lines = append(lines, l)
	}

	// PRIMARY KEY / UNIQUE constraints
	keys, err := rowStrings(ctx, q, `SELECT kc.name, kc.type, i.type_desc, col.name, CAST(ic.is_descending_key AS int)
		FROM `+d+`.sys.key_constraints kc
		JOIN `+d+`.sys.objects o ON o.object_id = kc.parent_object_id JOIN `+d+`.sys.schemas sc ON sc.schema_id = o.schema_id
		JOIN `+d+`.sys.indexes i ON i.object_id = kc.parent_object_id AND i.index_id = kc.unique_index_id
		JOIN `+d+`.sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id
		JOIN `+d+`.sys.columns col ON col.object_id = ic.object_id AND col.column_id = ic.column_id
		WHERE `+objFilter+` ORDER BY kc.type, kc.name, ic.key_ordinal`, s, t.Name)
	if err != nil {
		return "", err
	}
	for _, g := range groupRows(keys, 0) {
		kind := "UNIQUE"
		if strings.TrimSpace(g[0][1]) == "PK" {
			kind = "PRIMARY KEY"
		}
		lines = append(lines, fmt.Sprintf("    CONSTRAINT %s %s %s (%s)", msq(g[0][0]), kind, g[0][2], joinCols(g, 3, 4)))
	}

	// FOREIGN KEYs
	fks, err := rowStrings(ctx, q, `SELECT fk.name, pc.name, rs.name, rt.name, rc.name, fk.delete_referential_action_desc, fk.update_referential_action_desc
		FROM `+d+`.sys.foreign_keys fk
		JOIN `+d+`.sys.objects o ON o.object_id = fk.parent_object_id JOIN `+d+`.sys.schemas sc ON sc.schema_id = o.schema_id
		JOIN `+d+`.sys.foreign_key_columns fkc ON fkc.constraint_object_id = fk.object_id
		JOIN `+d+`.sys.columns pc ON pc.object_id = fkc.parent_object_id AND pc.column_id = fkc.parent_column_id
		JOIN `+d+`.sys.objects rt ON rt.object_id = fk.referenced_object_id JOIN `+d+`.sys.schemas rs ON rs.schema_id = rt.schema_id
		JOIN `+d+`.sys.columns rc ON rc.object_id = fkc.referenced_object_id AND rc.column_id = fkc.referenced_column_id
		WHERE `+objFilter+` ORDER BY fk.name, fkc.constraint_column_id`, s, t.Name)
	if err != nil {
		return "", err
	}
	for _, g := range groupRows(fks, 0) {
		var pcs, rcs []string
		for _, r := range g {
			pcs = append(pcs, msq(r[1]))
			rcs = append(rcs, msq(r[4]))
		}
		l := fmt.Sprintf("    CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s.%s (%s)", msq(g[0][0]), strings.Join(pcs, ", "),
			msq(g[0][2]), msq(g[0][3]), strings.Join(rcs, ", "))
		if a := g[0][5]; a != "NO_ACTION" {
			l += " ON DELETE " + strings.ReplaceAll(a, "_", " ")
		}
		if a := g[0][6]; a != "NO_ACTION" {
			l += " ON UPDATE " + strings.ReplaceAll(a, "_", " ")
		}
		lines = append(lines, l)
	}

	checks, err := rowStrings(ctx, q, `SELECT ck.name, ck.definition FROM `+d+`.sys.check_constraints ck
		JOIN `+d+`.sys.objects o ON o.object_id = ck.parent_object_id JOIN `+d+`.sys.schemas sc ON sc.schema_id = o.schema_id
		WHERE `+objFilter+` ORDER BY ck.name`, s, t.Name)
	if err != nil {
		return "", err
	}
	for _, c := range checks {
		lines = append(lines, fmt.Sprintf("    CONSTRAINT %s CHECK %s", msq(c[0]), c[1]))
	}

	var b strings.Builder
	fmt.Fprintf(&b, "CREATE TABLE %s (\n%s\n);", full, strings.Join(lines, ",\n"))

	idx, err := rowStrings(ctx, q, `SELECT i.name, CAST(i.is_unique AS int), i.type_desc, col.name, CAST(ic.is_descending_key AS int),
		CAST(ic.is_included_column AS int), COALESCE(i.filter_definition, '')
		FROM `+d+`.sys.indexes i
		JOIN `+d+`.sys.objects o ON o.object_id = i.object_id JOIN `+d+`.sys.schemas sc ON sc.schema_id = o.schema_id
		JOIN `+d+`.sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id
		JOIN `+d+`.sys.columns col ON col.object_id = ic.object_id AND col.column_id = ic.column_id
		WHERE `+objFilter+` AND i.is_primary_key = 0 AND i.is_unique_constraint = 0 AND i.type > 0
		ORDER BY i.name, ic.is_included_column, ic.key_ordinal, ic.index_column_id`, s, t.Name)
	if err != nil {
		return "", err
	}
	groups := groupRows(idx, 0)
	if len(groups) > 0 {
		b.WriteString("\n")
	}
	for _, g := range groups {
		var keyRows, incl [][]string
		for _, r := range g {
			if r[5] == "1" {
				incl = append(incl, r)
			} else {
				keyRows = append(keyRows, r)
			}
		}
		u := ""
		if g[0][1] == "1" {
			u = "UNIQUE "
		}
		fmt.Fprintf(&b, "\nCREATE %s%s INDEX %s ON %s (%s)", u, g[0][2], msq(g[0][0]), full, joinCols(keyRows, 3, 4))
		if len(incl) > 0 {
			fmt.Fprintf(&b, " INCLUDE (%s)", joinCols(incl, 3, -1))
		}
		if g[0][6] != "" {
			b.WriteString(" WHERE " + g[0][6])
		}
		b.WriteString(";")
	}
	return b.String(), nil
}

func mssqlType(name, maxLen, prec, scale string) string {
	switch name {
	case "varchar", "char", "varbinary", "binary":
		if maxLen == "-1" {
			return name + "(max)"
		}
		return name + "(" + maxLen + ")"
	case "nvarchar", "nchar":
		if maxLen == "-1" {
			return name + "(max)"
		}
		var n int
		fmt.Sscan(maxLen, &n)
		return fmt.Sprintf("%s(%d)", name, n/2)
	case "decimal", "numeric":
		return name + "(" + prec + "," + scale + ")"
	case "datetime2", "time", "datetimeoffset":
		return name + "(" + scale + ")"
	}
	return name
}

// groupRows groups consecutive rows sharing the value in column k.
func groupRows(rows [][]string, k int) [][][]string {
	var out [][][]string
	for _, r := range rows {
		if n := len(out); n > 0 && out[n-1][0][k] == r[k] {
			out[n-1] = append(out[n-1], r)
		} else {
			out = append(out, [][]string{r})
		}
	}
	return out
}

func joinCols(rows [][]string, nameCol, descCol int) string {
	var parts []string
	for _, r := range rows {
		p := msq(r[nameCol])
		if descCol >= 0 && r[descCol] == "1" {
			p += " DESC"
		}
		parts = append(parts, p)
	}
	return strings.Join(parts, ", ")
}

// ---------------------------------------------------------------- Oracle

func (oracleDialect) DDL(ctx context.Context, q *sql.Conn, schema string, t Table) (string, error) {
	// Session-level transforms: leave out storage clutter, end with ';'.
	_, _ = q.ExecContext(ctx, `BEGIN
		DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'SEGMENT_ATTRIBUTES', FALSE);
		DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'STORAGE', FALSE);
		DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'SQLTERMINATOR', TRUE);
		DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'PRETTY', TRUE);
	END;`)
	objType := "TABLE"
	switch t.Type {
	case "VIEW":
		objType = "VIEW"
	case "MATERIALIZED VIEW":
		objType = "MATERIALIZED_VIEW"
	}
	var ddl sql.NullString
	if err := q.QueryRowContext(ctx, "SELECT DBMS_METADATA.GET_DDL(:1, :2, :3) FROM dual", objType, t.Name, schema).Scan(&ddl); err != nil {
		return "", err
	}
	parts := []string{strings.TrimSpace(ddl.String)}
	if objType == "TABLE" {
		// Indexes that don't back a constraint (those are already in the table DDL).
		idx, _ := scanStrings(ctx, q, `SELECT index_name FROM all_indexes i WHERE owner = :1 AND table_name = :2
			AND index_type NOT LIKE 'LOB%'
			AND NOT EXISTS (SELECT 1 FROM all_constraints c WHERE c.owner = i.table_owner AND c.table_name = i.table_name AND c.index_name = i.index_name)
			ORDER BY index_name`, schema, t.Name)
		for _, name := range idx {
			var d sql.NullString
			if q.QueryRowContext(ctx, "SELECT DBMS_METADATA.GET_DDL('INDEX', :1, :2) FROM dual", name, schema).Scan(&d) == nil {
				parts = append(parts, strings.TrimSpace(d.String))
			}
		}
		var cm sql.NullString
		if q.QueryRowContext(ctx, "SELECT DBMS_METADATA.GET_DEPENDENT_DDL('COMMENT', :1, :2) FROM dual", t.Name, schema).Scan(&cm) == nil {
			parts = append(parts, strings.TrimSpace(cm.String))
		}
	}
	return strings.Join(parts, "\n\n"), nil
}

// ---------------------------------------------------------------- SQLite

func (sqliteDialect) DDL(ctx context.Context, q *sql.Conn, schema string, t Table) (string, error) {
	rows, err := rowStrings(ctx, q, `SELECT type, sql FROM `+quoteWith(schema, `"`, `"`)+`.sqlite_master
		WHERE (name = ? OR tbl_name = ?) AND sql IS NOT NULL`, t.Name, t.Name)
	if err != nil {
		return "", err
	}
	order := map[string]int{"table": 0, "view": 0, "index": 1, "trigger": 2}
	sort.SliceStable(rows, func(i, j int) bool { return order[rows[i][0]] < order[rows[j][0]] })
	var parts []string
	for _, r := range rows {
		parts = append(parts, strings.TrimSpace(r[1])+";")
	}
	return strings.Join(parts, "\n\n"), nil
}
